import { describe, expect, test } from "bun:test";
import { gitWipRepos, v } from "./helpers/git-wip-repos";

const { feature } = gitWipRepos();

// Guard against a vacuous pass: the fixture repo must be a live, non-protected checkout (see git-wip-no-ask.test.ts).
test("fixture: a plain commit on the feature repo is silent", () => {
  expect(v("git commit -m x", feature)).toBe("allow");
});

describe("only plain add/commit are exempt", () => {
  test.each([
    "git commit --amend -m x",
    "git commit --amend --no-edit",
    "git commit --no-verify -m x",
    "git commit -n -m x",
    "git commit -an -m x",
    "git add -f .env",
    "git add --force .env",
    "git add -Af x",
    // Unique-prefix abbreviations git accepts for the risky long flags (gitcli "Abbreviating long options").
    "git commit --amen -m x",
    "git commit --am -m x",
    "git commit --no-ver -m x",
    "git commit --no-post -m x",
    "git add --forc .env",
    "git add --fo .env",
    // Any global option between `git` and the subcommand (other program, config, repository).
    "git --exec-path=/tmp/evil commit -m x",
    "git --exec-path /tmp/evil commit -m x",
    "git --config-env=core.hooksPath=HP commit -m x",
    "git --bare commit -m x",
    "git -p commit -m x",
    "git --no-pager add -A",
    "\"git\" --exec-path=/tmp/evil commit -m x",
    "/usr/bin/git --exec-path=/tmp/evil commit -m x",
    "git add -A && git --exec-path=/tmp/evil commit -m x",
    "git -C /tmp/elsewhere commit -m x",
    "git --git-dir=/x/.git commit -m x",
    "git --work-tree=/x commit -m x",
    "git -c core.hooksPath=/dev/null commit -m x",
    "GIT_DIR=/x/.git git commit -m x",
    // Environment prefixes: `expand` strips them from the segment, yet they change what the commit runs.
    "HOME=/tmp/evilhome git commit -qm x",
    "PATH=/tmp/evilbin:/usr/bin git commit -m x",
    "HUSKY=0 git commit -m x",
    "SKIP=lint git commit -m x",
    "LD_PRELOAD=/tmp/x.so git commit -m x",
    "BASH_ENV=/tmp/x git commit -m x",
    "XDG_CONFIG_HOME=/tmp/x git commit -m x",
    "EDITOR=/tmp/evil git commit",
    "PAGER=/tmp/evil git log && git commit -m x",
    "git add -A && HOME=/tmp/x git commit -m x",
    "A=1 B=2 git add -A",
    "git commit -m x 2>&1 & HOME=/tmp/e git commit -m y",
    "git commit -m x &> /dev/null; HOME=/tmp/e git commit -m y",
    // Assignments or reserved words behind a group opener or `!`: proven to skip hooks at runtime.
    "{ HOME=/tmp/evilhome git commit -qm brace; }",
    "! HOME=/tmp/evilhome git commit -qm bang",
    "git status && { PATH=/tmp/e:/usr/bin git commit -m x; }",
    "git commit -m x\n{ HOME=/tmp/e git commit -m y; }",
    "( HOME=/tmp/e git commit -m x )",
    "if true; then HOME=/tmp/e git commit -m x; fi",
    "time git commit -m x",
    "exec git commit -m x",
    "command git commit -m x",
    "env -i git commit -m x",
    "export HOME=/tmp/e; git commit -m x",
    "cd ../main && git commit -m x",
    "git commit -m x && git push origin HEAD",
    "git commit -m x; git checkout main",
    "env --chdir=/some/other/repo git commit -am x",
    "timeout 5 git commit -m x",
    "nice git commit -m x",
    "/usr/bin/git commit -m x",
    "git commit -m x --{amend,quiet}",
    "git commit -m x --amend{,}",
    "git commit -m x ${Y:---amend}",
    "git commit -m x $Y",
    "git commit -m x \"$Y\"",
    "git commit -m x -{n,v}",
    "git add *",
    "git commit -m x --{amend,\"quiet x\"}",
    "git commit -m x --{amend,'q x'}",
    "git commit -m \"x\" --a{mend,\" b\"}",
    "git commit -m x -{n,\"v x\"}",
    "git add -{f,\" x\"} .",
    "git commit -m x && git diff --output=/tmp/x",
    "git commit -m x && git log --out=/tmp/x",
    "git commit -m x && git diff --ext-diff",
    "git log -p --textconv && git commit -m x",
    "git switch main && git commit -am x",
    "git symbolic-ref HEAD refs/heads/main && git commit -m x",
    "git commit -m x && git update-ref refs/heads/main HEAD~5",
    "git commit -m x && git update-ref -d refs/heads/main",
    "git commit -m x && git send-pack origin HEAD:main",
    "git commit -m x && git branch -f main HEAD",
    "git commit -m x && git branch -M main2 main",
    "git commit -m x && git fetch origin +main:main",
    "git commit -m x && git pull --rebase",
    "git commit -m x && git filter-branch -f HEAD",
    "git commit -m x && git reflog expire --expire=now --all",
    "git commit -m x && git gc --prune=now",
    "git config core.hooksPath /tmp/h && git commit -m x",
    "git worktree add ../x main && git commit -m x",
    "git add -A && git stash",
    "git commit -m \"$(git push origin main)\"",
    "sh -c 'git commit -m x && git merge other'",
    "git commit -m x | git reset HEAD~1",
    "git push origin HEAD",
    "git checkout main",
    "git merge other",
    "git stash",
    "git restore .",
    "git rm a.ts",
    "git revert HEAD",
    "git cherry-pick abc",
    "git branch -d x",
    "git rebase main",
    "git reset HEAD~1",
  ])("%s keeps asking or blocking", (cmd) => {
    expect(v(cmd, feature)).not.toBe("allow");
  });
});
