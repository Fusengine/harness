import { test, expect } from "bun:test";
import { tmpdir } from "node:os";
import { mkdtempSync, writeFileSync, rmSync, mkdirSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { getFileDesc } from "../src/runtime/lifecycle/cartographer/fs-util";
import {
  DEFAULT_CARTO_FULL_READ_MAX_BYTES,
  readDescription,
  readSmallRegularFile,
  resolveCartoFullReadMaxBytes,
} from "../src/runtime/lifecycle/cartographer/bounded-read";
import { MIB, sparse } from "./helpers/carto-rss";

const tmp = (): string => mkdtempSync(join(tmpdir(), "fh-carto-br-"));
/** Run `fn` with a fresh temp dir, always cleaned. */
function withDir(fn: (dir: string) => void): void {
  const dir = tmp();
  try {
    fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test("resolveCartoFullReadMaxBytes: default 1 MiB, env override, invalid falls back", () => {
  expect(DEFAULT_CARTO_FULL_READ_MAX_BYTES).toBe(MIB);
  expect(resolveCartoFullReadMaxBytes({})).toBe(MIB);
  expect(resolveCartoFullReadMaxBytes({ FUSE_CARTO_FULL_READ_MAX_BYTES: "2048" })).toBe(2048);
  expect(resolveCartoFullReadMaxBytes({ FUSE_CARTO_FULL_READ_MAX_BYTES: "abc" })).toBe(MIB);
  expect(resolveCartoFullReadMaxBytes({ FUSE_CARTO_FULL_READ_MAX_BYTES: "-5" })).toBe(MIB);
});

test("files at or below the cap are read whole; larger ones give the cap-sized prefix cut at the last newline", () => {
  withDir((dir) => {
    const p = join(dir, "a.ts");
    const body = `// head\n${"x".repeat(100)}\nlast line\n`;
    writeFileSync(p, body);
    expect(readDescription(p, body.length)).toEqual({ text: body, truncated: false });
    const cut = readDescription(p, 50);
    expect(cut.truncated).toBe(true);
    expect(cut.text).toBe("// head");
  });
});

test("a multi-byte character cut at the prefix end is dropped, not mangled", () => {
  withDir((dir) => {
    const p = join(dir, "u.ts");
    writeFileSync(p, `// ok\n${"é".repeat(100)}\n`);
    const { text } = readDescription(p, 9);
    expect(text).toBe("// ok");
    expect(text.includes("�")).toBe(false);
  });
});

test("a single line longer than the cap yields no description (never a half-read line)", () => {
  withDir((dir) => {
    writeFileSync(join(dir, "long.ts"), `// ${"a".repeat(2 * MIB)}\nexport {};\n`);
    expect(getFileDesc(join(dir, "long.ts"))).toBe("");
  });
});

test("large text files: description from the first MiB (md frontmatter, md heading, ts comment)", () => {
  withDir((dir) => {
    const filler = "z".repeat(100).concat("\n").repeat(25_000); // ~2.4 MiB
    writeFileSync(join(dir, "big.md"), `---\ndescription: Big doc\n---\n# Title\n${filler}`);
    writeFileSync(join(dir, "big.ts"), `// big module\n${filler}`);
    writeFileSync(join(dir, "head.md"), `# Heading\n${filler}`);
    const yaml70k = "k: v\n".repeat(14_000); // ~70 KiB frontmatter, closed inside the first MiB
    writeFileSync(join(dir, "fm70.md"), `---\ndescription: Long frontmatter\n${yaml70k}---\n# T\n${filler}`);
    writeFileSync(join(dir, "late.md"), `intro\n${"p\n".repeat(50_000)}# Late heading\n${filler}`);
    expect(getFileDesc(join(dir, "big.md"))).toBe("Big doc");
    expect(getFileDesc(join(dir, "big.ts"))).toBe("big module");
    expect(getFileDesc(join(dir, "head.md"))).toBe("Heading");
    expect(getFileDesc(join(dir, "fm70.md"))).toBe("Long frontmatter");
    expect(getFileDesc(join(dir, "late.md"))).toBe("Late heading");
  });
});

test("counter-example: a >1 MiB .md with an unclosed-in-prefix frontmatter never takes a YAML comment as heading", () => {
  withDir((dir) => {
    const yaml = "k: v\n".repeat(250_000); // ~1.2 MiB of frontmatter
    writeFileSync(join(dir, "fm.md"), `---\n# generated by tool x\ndescription: the real one\n${yaml}---\n# H\n`);
    expect(getFileDesc(join(dir, "fm.md"))).toBe("");
  });
});

test("counter-example: a comment crossing the old 64 KiB boundary is no longer cut", () => {
  withDir((dir) => {
    // the comment line starts just before byte 65536 and ends after it
    writeFileSync(join(dir, "c.ts"), `${"x".repeat(65_530)}\n// description text long enough here\n`.padEnd(2 * MIB, "\n"));
    expect(getFileDesc(join(dir, "c.ts"))).toBe("description text long enough here");
  });
});

test("large binary-looking files yield no description (NUL byte, %PDF- magic, zeros)", () => {
  withDir((dir) => {
    writeFileSync(join(dir, "nul.ts"), Buffer.concat([Buffer.from("// looks fine\n"), Buffer.from([0]), Buffer.alloc(100, 97)]));
    writeFileSync(join(dir, "pdf.md"), Buffer.from(`%PDF-1.7\n# Heading\n${"a".repeat(100)}`));
    sparse(join(dir, "zeros.py"), 3 * MIB);
    expect(readDescription(join(dir, "nul.ts"), 10).text).toBe("");
    expect(readDescription(join(dir, "pdf.md"), 10).text).toBe("");
    expect(getFileDesc(join(dir, "zeros.py"))).toBe("");
  });
});

test("non-regular and missing files are skipped without being opened", () => {
  withDir((dir) => {
    const fifo = join(dir, "pipe.ts");
    expect(Bun.spawnSync(["mkfifo", fifo]).exitCode).toBe(0);
    expect(getFileDesc(fifo)).toBe("");
    mkdirSync(join(dir, "d.ts"));
    expect(getFileDesc(join(dir, "d.ts"))).toBe("");
    expect(getFileDesc(join(dir, "missing.ts"))).toBe("");
  });
});

test("unsupported extensions are never read, however large", () => {
  withDir((dir) => {
    sparse(join(dir, "huge.pdf"), 64 * MIB);
    sparse(join(dir, "huge.bin"), 64 * MIB);
    expect(getFileDesc(join(dir, "huge.pdf"))).toBe("");
    expect(getFileDesc(join(dir, "huge.bin"))).toBe("");
  });
});

test("readSmallRegularFile: small regular file read, device / oversize / missing / dir are absent", () => {
  withDir((dir) => {
    writeFileSync(join(dir, "ok.md"), "hello");
    symlinkSync(join(dir, "ok.md"), join(dir, "link.md"));
    symlinkSync("/dev/zero", join(dir, "zero.md"));
    sparse(join(dir, "big.md"), 4 * MIB);
    mkdirSync(join(dir, "dir.md"));
    expect(readSmallRegularFile(join(dir, "ok.md"))).toBe("hello");
    expect(readSmallRegularFile(join(dir, "link.md"))).toBe("hello");
    expect(readSmallRegularFile(join(dir, "zero.md"))).toBeUndefined();
    expect(readSmallRegularFile(join(dir, "big.md"))).toBeUndefined();
    expect(readSmallRegularFile(join(dir, "big.md"), 8 * MIB)?.length).toBe(4 * MIB);
    expect(readSmallRegularFile(join(dir, "dir.md"))).toBeUndefined();
    expect(readSmallRegularFile(join(dir, "missing.md"))).toBeUndefined();
  });
});
