/**
 * Ecosystem (plugin) map generation (fs). Ports `generate_map.py`: scans every
 * installed plugin into a level-1 `.cartographer/index.md` + per-plugin level-2+
 * trees, preserving enriched descriptions. Reuses `findMarketplacePlugins`,
 * `readPluginMeta`, `scanPlugin`, `mergeLines`, `writePluginMap`.
 */
import { lstatSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { isRealDir, isSafeOutputDir, isSafePathSegment, writeFileReplacing } from "./safe-write";
import { findMarketplacePlugins, readPluginMeta } from "./detect";
import { scanPlugin } from "./scan";
import { mergeLines } from "./merge";
import { writePluginMap } from "./write-plugin-map";

/** Plugin directories of `dir`: real ones to scan, and symlinked ones (never followed) to report as skipped. */
function pluginDirs(dir: string): { real: string[]; skipped: string[] } {
  let entries: string[] = [];
  try { entries = readdirSync(dir); } catch { return { real: [], skipped: [] }; }
  const visible = entries
    .filter((n) => !n.startsWith("_") && !n.startsWith("."))
    .sort((a, b) => a.localeCompare(b, "en"));
  const real = visible.filter((n) => isRealDir(join(dir, n)));
  const skipped = visible.filter((n) => {
    try { return lstatSync(join(dir, n)).isSymbolicLink() && statSync(join(dir, n)).isDirectory(); } catch { return false; }
  });
  return { real, skipped };
}

function utcStamp(now: number): string {
  return new Date(now).toISOString().slice(0, 16).replace("T", " ");
}

/**
 * Generate the plugin ecosystem map under `<pluginsDir>/.cartographer`.
 * @param now - Clock for the banner timestamp.
 * @param pluginsDirOverride - Override for the marketplace plugins directory.
 * @returns The map navigation context, or "".
 */
export function generateEcosystemMap(now: number, pluginsDirOverride?: string): string {
  const pluginsDir = resolve(pluginsDirOverride ?? findMarketplacePlugins());
  try { if (!statSync(pluginsDir).isDirectory()) return ""; } catch { return ""; }
  const outputDir = join(pluginsDir, ".cartographer");
  if (!isSafeOutputDir(outputDir)) return "";
  mkdirSync(outputDir, { recursive: true });
  const { real: dirs, skipped } = pluginDirs(pluginsDir);
  const lines = [`# Ecosystem Map (${dirs.length} plugins)\n`, `> Auto-generated by cartographer — ${utcStamp(now)}\n`];
  for (const name of dirs) {
    const pluginPath = join(pluginsDir, name);
    const [version, pkgName] = readPluginMeta(pluginPath);
    // plugin.json's name is untrusted: used as a path component only when it is one; else the directory name.
    const display = pkgName && isSafePathSegment(pkgName) ? pkgName : name;
    if (!isSafePathSegment(display)) continue;
    const items = scanPlugin(pluginPath);
    const agents = items.filter(([t]) => t === "agent").map(([, n]) => n);
    const ver = version ? ` (v${version})` : "";
    lines.push(`- [${display}](./${display}/index.md)${ver} → ${agents.length ? agents.join(", ") : "(no agents)"}`);
    writePluginMap(outputDir, display, version, items, pluginPath);
    writePluginMap(pluginPath, ".cartographer", version, items, pluginPath);
  }
  for (const name of skipped) lines.push(`- ${name} — skipped (symlinked directory)`);
  const indexPath = join(outputDir, "index.md");
  writeFileReplacing(indexPath, mergeLines(lines, indexPath).join("\n") + "\n");
  return `Project map: .cartographer/project/index.md — navigate project files. ` +
    `Plugin skills map: ${outputDir}/index.md — navigate agent skills. ` +
    `Branches link to deeper index.md, leaves link to real files.`;
}
